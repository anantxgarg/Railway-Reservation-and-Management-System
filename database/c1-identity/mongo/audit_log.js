const COLL = "audit_log";

const validator = {
  $jsonSchema: {
    bsonType: "object",
    required: ["audit_id", "action", "resource_type", "timestamp", "result", "metadata"],
    additionalProperties: false,
    properties: {
      _id:           { bsonType: "objectId" },
      audit_id:      { bsonType: "string", minLength: 1,
                       description: "Unique event id (e.g. a UUID generated by the backend)" },
      user_id:       { bsonType: ["string", "null"],
                       description: "users.user_id as a string; null when no authenticated user (e.g. failed login for unknown e-mail)" },
      action:        { bsonType: "string", pattern: "^[A-Z][A-Z_]*$",
                       description: "e.g. LOGIN, LOGIN_FAILED, USER_CREATED, ROLE_CHANGED" },
      resource_type: { bsonType: "string", pattern: "^[A-Z][A-Z_]*$",
                       description: "e.g. USER, ROLE, PERMISSION, MASTER_DATA" },
      resource_id:   { bsonType: ["string", "null"] },
      timestamp:     { bsonType: "date" },
      result:        { enum: ["SUCCESS", "FAILURE"] },
      metadata:      { bsonType: "object" },
      ip_address:    { bsonType: ["string", "null"] },
      device_info:   { bsonType: ["string", "null"], maxLength: 500 }
    }
  }
};

const exists = db.getCollectionNames().includes(COLL);
if (!exists) {
  db.createCollection(COLL, {
    validator,
    validationLevel: "strict",
    validationAction: "error"
  });
  print(`created ${COLL}`);
} else {
  db.runCommand({ collMod: COLL, validator, validationLevel: "strict", validationAction: "error" });
  print(`updated validator on ${COLL}`);
}

const c = db.getCollection(COLL);
c.createIndex({ audit_id: 1 },                { unique: true, name: "uq_audit_id" });
c.createIndex({ user_id: 1, timestamp: -1 },  { name: "ix_user_time" });
c.createIndex({ action: 1,  timestamp: -1 },   { name: "ix_action_time" });
print("indexes ensured");

