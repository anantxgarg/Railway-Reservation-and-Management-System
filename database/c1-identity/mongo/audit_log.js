//   action string · resource_type string · resource_id string|null
//   timestamp date · result SUCCESS|FAILURE · metadata object
//   ip_address string · device_info string
//
// NEVER put passwords, password hashes, JWTs, refresh tokens or reset
// tokens in metadata.
